package EX_02092025_Main_method;

public class Lab027_forloop_7 {
    public static void main(String[] args) {
        //Even and ODD
        for (int i =0; i<=50 ;i++){
            if (i%2==0){
                System.out.println("Even");
            }
            else{
                System.out.println("ODD");
            }
        }
    }
}
